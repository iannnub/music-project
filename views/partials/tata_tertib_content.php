    <div class="tatib-section">
        <h4>A. TATA TERTIB SISWA</h4>
        <ol>
            <li>Siswa wajib hadir sesuai hari dan jam pembelajaran yang telah disepakati.</li>
            <li>Siswa diharapkan datang 5 sampai 10 menit sebelum pembelajaran dimulai.</li>
            <li>Keterlambatan siswa tidak menambah durasi atau mengubah jam selesai les.</li>
            <li>Siswa wajib mengikuti arahan mentor dan menjaga sikap selama pembelajaran.</li>
            <li>Siswa dilarang berkata kasar, mengganggu siswa lain, atau melakukan tindakan yang tidak sopan.</li>
            <li>Siswa wajib menjaga kebersihan, keamanan, dan seluruh fasilitas tempat les.</li>
            <li>Siswa tidak diperbolehkan menggunakan alat musik atau perlengkapan tanpa izin mentor.</li>
        </ol>
    </div>

    <div class="tatib-section">
        <h4>B. TATA TERTIB WALI MURID</h4>
        <ol>
            <li>Wali murid wajib memastikan siswa hadir sesuai jadwal dan menjemput anak tepat waktu.</li>
            <li>Izin ketidakhadiran atau permohonan perubahan jadwal disampaikan kepada admin KakYo Lesson, bukan dengan mengubah jadwal secara sepihak kepada mentor.</li>
            <li>Wali murid diharapkan menyampaikan kritik, saran, dan keluhan melalui pengelola atau admin dengan bahasa yang sopan.</li>
            <li>Wali murid tidak diperkenankan mengganggu proses pembelajaran yang sedang berlangsung.</li>
        </ol>
    </div>

    <div class="tatib-section">
        <h4>C. KETENTUAN PEMBAYARAN DAN ADMINISTRASI</h4>
        <ol>
            <li>Pembayaran SPP dilakukan sesuai nominal dan tanggal jatuh tempo yang telah diinformasikan oleh KakYo Lesson.</li>
            <li>Bukti pembayaran wajib dikirimkan kepada admin untuk pencatatan administrasi.</li>
            <li>Apabila mengalami kendala pembayaran, wali murid diharapkan menghubungi admin sebelum jatuh tempo.</li>
            <li>Tunggakan pembayaran dapat menyebabkan jadwal pembelajaran ditangguhkan sementara setelah ada pemberitahuan kepada wali murid.</li>
        </ol>
    </div>

    <div class="tatib-section">
        <h4>D. KETENTUAN IZIN, KETIDAKHADIRAN, DAN PENGGANTIAN JADWAL</h4>
        <ol>
            <li>Permohonan izin siswa disampaikan paling lambat H-2 sebelum jadwal les agar dapat dipertimbangkan untuk jadwal pengganti.</li>
            <li>Izin yang disampaikan kurang dari H-2, ketidakhadiran tanpa kabar, atau pembatalan mendadak pada prinsipnya dihitung sebagai pertemuan berjalan.</li>
            <li>Jadwal pengganti hanya dapat diberikan berdasarkan ketersediaan waktu mentor dan tempat les, serta harus dikonfirmasi oleh admin.</li>
            <li>Apabila mentor berhalangan hadir, KakYo Lesson akan menginformasikan kepada wali murid dan mengatur jadwal pengganti atau solusi lain.</li>
            <li>Apabila kegiatan belajar dibatalkan oleh pihak KakYo Lesson, pertemuan tersebut tidak mengurangi hak pertemuan siswa dan akan dijadwalkan ulang.</li>
        </ol>
    </div>

    <div class="tatib-section">
        <h4>E. KETENTUAN KHUSUS LES PRIVAT / HOME COURSE</h4>
        <ol>
            <li>Wali murid memastikan tempat belajar aman, nyaman, dan siap digunakan sebelum mentor tiba.</li>
            <li>Ketersediaan alat musik di rumah mengikuti kesepakatan layanan saat pendaftaran. Jika alat disediakan oleh KakYo Lesson, penggunaannya mengikuti arahan mentor.</li>
            <li>Perubahan alamat atau lokasi les wajib diinformasikan dan disetujui terlebih dahulu oleh pengelola.</li>
        </ol>
    </div>

    <div class="tatib-section">
        <h4>F. HAK SISWA DAN WALI MURID</h4>
        <ol>
            <li>Siswa berhak memperoleh pembelajaran sesuai program dan jadwal yang telah disepakati.</li>
            <li>Siswa berhak diperlakukan dengan sopan, aman, dan tanpa kekerasan atau tindakan merendahkan.</li>
            <li>Wali murid berhak memperoleh informasi mengenai jadwal, administrasi, serta perkembangan belajar siswa secara wajar.</li>
            <li>Wali murid berhak menyampaikan pertanyaan, kritik, dan saran melalui saluran komunikasi resmi KakYo Lesson.</li>
        </ol>
    </div>

    <div class="tatib-section">
        <h4>G. PENGHENTIAN LES DAN PENYELESAIAN PERMASALAHAN</h4>
        <ol>
            <li>Wali murid yang berencana menghentikan les wajib menginformasikan kepada admin agar administrasi dan jadwal dapat diperbarui.</li>
            <li>Setiap permasalahan terkait pembelajaran, mentor, jadwal, atau pembayaran diselesaikan terlebih dahulu melalui komunikasi dengan admin atau pengelola.</li>
            <li>KakYo Lesson berhak memberikan teguran atau mengevaluasi keberlanjutan layanan apabila terjadi pelanggaran tata tertib yang berulang, dengan mempertimbangkan klarifikasi dari pihak terkait.</li>
        </ol>
